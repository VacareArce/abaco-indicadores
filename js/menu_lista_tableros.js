// contenido de los tableros
function updateContent(tipo) {
    if (window.handleBQContentType && window.handleBQContentType(tipo)) {
        return;
    }

    // Obtener todos los elementos iframe
    const iframes = document.querySelectorAll('iframe');

    // Ocultar todos los iframes
    iframes.forEach(iframe => {
        iframe.style.display = 'none';
    });

    // Remover la clase 'active' de todos los iconos
    const iconLinks = document.querySelectorAll('.icon-link');
    iconLinks.forEach(iconLink => {
        iconLink.classList.remove('active');
    });

    let iframeId;
    if (tipo === 'grafica') {
        // En caso de gráfica, usar un id especial
        iframeId = 'tablero';
    } else {
        // Para otros tipos, usar un id con el prefijo 'iframe-'
        iframeId = `iframe-${tipo}`;
    }

    // Obtener el nuevo iframe y el nuevo icono a mostrar y activar
    const newIframe = document.getElementById(iframeId);
    const newIconLink = document.getElementById(tipo);

    // Mostrar el nuevo iframe y añadir la clase 'active' al nuevo icono
    if (newIframe) {
        newIframe.style.display = 'block';
    }

    if (tipo !== 'grafica' && window.hideBQChartView) {
        window.hideBQChartView();
    }

    if (newIconLink) {
        newIconLink.classList.add('active');
    }
	console.log("-"+iframeId);
}
